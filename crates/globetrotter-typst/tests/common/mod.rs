//! Helpers for comparing generated Typst modules with checked-in fixtures.

use color_eyre::eyre;

/// The header line that records which generator version wrote a module.
const VERSION_PREFIX: &str = "// Generated by globetrotter v";

/// Returns `fixture` with its recorded generator version replaced by the version under test.
///
/// Fixtures keep the version they were generated with, so a release bump never invalidates them.
/// The comparison still checks that a generated header names the running generator.
pub fn with_current_version(fixture: &str) -> eyre::Result<String> {
    let (head, rest) = fixture
        .split_once(VERSION_PREFIX)
        .ok_or_else(|| eyre::eyre!("fixture has no `{VERSION_PREFIX}` header"))?;
    // The version itself contains dots, so the header ends at the first dot before a newline.
    let (_, tail) = rest
        .split_once(".\n")
        .ok_or_else(|| eyre::eyre!("fixture version header does not end with `.`"))?;
    Ok(format!(
        "{head}{VERSION_PREFIX}{}.\n{tail}",
        env!("CARGO_PKG_VERSION")
    ))
}
